import { tool } from "@rsmrtk/plugin"
import { writeFile, mkdir } from "node:fs/promises"
import path from "node:path"
import { settings } from "./_shared/settings"
import * as Slo from "./_shared/slo"

// Ported from naki-cli (naki/agent/tools/postmortem_draft.py).
//
// Not ported: the "actions taken" section built from naki's own audit log
// (naki/agent/audit.py) — box has no equivalent audit log of tool calls
// yet, so that section is simply omitted rather than faked. The error
// budget section is kept in full, reusing the slo.ts module already built
// for slo_status.

function section(heading: string, body?: string): string | null {
  if (!body) return null
  return `## ${heading}\n\n${body}`
}

function listSection(heading: string, items?: string[]): string | null {
  if (!items?.length) return null
  return `## ${heading}\n\n${items.map((i) => `- ${i}`).join("\n")}`
}

async function budgetSection(): Promise<string | null> {
  if (!settings.prometheusUrl) return null
  const { slos } = await Slo.load()
  const names = Object.keys(slos).sort()
  if (!names.length) return null

  const lines: string[] = []
  for (const name of names) {
    const status = await Slo.measure(slos[name]!)
    if (status.sli === null) {
      lines.push(`- ${name}: could not be measured at drafting time`)
      continue
    }
    const remaining = (Slo.budgetRemaining(status) ?? 0) * 100
    lines.push(`- ${name}: SLI ${(status.sli * 100).toFixed(3)}% against a ${slos[name]!.objective}% objective — ${remaining.toFixed(1)}% of the error budget remains`)
  }
  if (!lines.length) return null
  return (
    "## Error budget impact\n\n" +
    lines.join("\n") +
    "\n\n_Measured from Prometheus when this draft was generated, not at the time of the incident — re-check if you are filing this much later._"
  )
}

export default tool({
  description: `Turn a finished investigation into a structured postmortem document — the artifact the team actually has to file after an incident. Fill the fields from what you actually found; leave a field out rather than inventing it.`,
  args: {
    title: tool.schema.string().describe("Short incident title."),
    summary: tool.schema.string().describe("Two or three sentences: what happened."),
    impact: tool.schema.string().describe("Who/what was affected, and for how long.").optional(),
    root_cause: tool.schema.string().describe("The cause you established, with the evidence.").optional(),
    timeline: tool.schema.array(tool.schema.string()).describe("Ordered events, each like '14:12 — p99 latency tripled'.").optional(),
    remediation: tool.schema.string().describe("What fixed it, or what would.").optional(),
    action_items: tool.schema.array(tool.schema.string()).describe("Follow-ups to stop it recurring.").optional(),
    file_path: tool.schema.string().describe("Optional path to write the document to. Returns the text either way.").optional(),
    evidence_hours: tool.schema
      .number()
      .describe("How far back the incident window reaches, in hours (default 6). Pass 0 to leave the error-budget section out.")
      .optional(),
  },
  async execute(args, ctx) {
    const today = new Date().toISOString().slice(0, 10)
    const parts = [`# Postmortem: ${args.title || "Untitled incident"}`, `_Drafted ${today}_`]

    for (const s of [
      section("Summary", args.summary),
      section("Impact", args.impact),
      listSection("Timeline", args.timeline),
      section("Root cause", args.root_cause),
      section("Remediation", args.remediation),
      listSection("Action items", args.action_items),
    ]) {
      if (s) parts.push(s)
    }

    const hours = args.evidence_hours ?? 6
    if (hours > 0) {
      try {
        const budget = await budgetSection()
        if (budget) parts.push(budget)
      } catch {
        // a postmortem that fails to render because Prometheus is unreachable
        // is worse than one missing a section
      }
    }

    parts.push("---\n_Draft generated by box from the investigation above (ported from naki). Verify every claim before circulating._")
    const document = parts.join("\n\n")

    if (!args.file_path) return { title: args.title, output: document }

    // A model-chosen path must stay inside the project and be approved by the
    // user: this tool writes without going through the host's edit /
    // external_directory checks, so it has to ask for itself.
    const filePath = path.resolve(ctx.directory, args.file_path.replace(/^~(?=$|\/)/, process.env.HOME ?? "~"))
    const rel = path.relative(ctx.directory, filePath)
    if (rel === "" || rel === ".." || rel.startsWith(".." + path.sep) || path.isAbsolute(rel)) {
      return { title: args.title, output: `${document}\n\n(Refused to write ${filePath}: outside the project directory ${ctx.directory}. Use a path inside the project.)` }
    }
    await ctx.ask({
      permission: "postmortem_draft",
      patterns: [rel],
      always: [rel],
      metadata: { file_path: filePath },
    })
    try {
      await mkdir(path.dirname(filePath), { recursive: true })
      await writeFile(filePath, document, { flag: "wx" })
    } catch (exc: any) {
      return { title: args.title, output: `${document}\n\n(Could not write to ${filePath}: ${exc.message})` }
    }
    return { title: args.title, output: `${document}\n\n(Written to ${filePath})` }
  },
})
